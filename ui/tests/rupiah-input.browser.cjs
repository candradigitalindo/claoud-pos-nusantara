// Start Vite, then: RUPIAH_TEST_URL=http://127.0.0.1:4193 node tests/rupiah-input.browser.cjs
// Requires Playwright with Chromium. The fixture never connects to an API/database.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const base = process.env.RUPIAH_TEST_URL || 'http://127.0.0.1:4193'

;(async () => {
  const browser = await chromium.launch({ args: ['--no-sandbox'] })
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } })
    page.setDefaultTimeout(10000)
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => {
      if (message.text().includes('[Vue warn]')) errors.push(message.text())
    })
    await page.goto(`${base}/tests/fixtures/rupiah-input.html`)
    const state = async () => JSON.parse(await page.locator('#state').textContent())
    const input = label => page.getByRole('textbox', { name: label, exact: true })
    const amount = input('Nominal')
    const valid = () => amount.evaluate(el => el.checkValidity())
    assert.equal(await input('Harga satuan').inputValue(), '1.234,56')
    assert.equal(await amount.getAttribute('name'), 'amount')
    await amount.fill('')
    await page.getByRole('button', { name: 'Simpan nominal', exact: true }).click()
    assert.equal((await state()).submits, 0)
    assert.equal(await valid(), false)
    console.log('PASS label, nilai desimal awal, dan validasi wajib')

    await amount.fill('')
    await amount.pressSequentially('1000000')
    assert.equal(await amount.inputValue(), '1.000.000')
    assert.equal((await state()).amount, 1000000)
    assert.equal((await state()).amountType, 'number')
    await input('Harga satuan').focus()
    assert.equal((await state()).seenOnChange, 1000000)
    assert((await state()).changes > 0)
    await page.getByRole('button', { name: 'Simpan nominal', exact: true }).click()
    assert.deepEqual((await state()).payload, { amount: 1000000, price: 1234.56 })
    console.log('PASS pemisah ribuan saat mengetik, event perubahan, dan payload numerik')

    async function paste(text) {
      await amount.fill('')
      await amount.focus()
      await amount.evaluate((el, text) => {
        const clipboardData = new DataTransfer()
        clipboardData.setData('text/plain', text)
        el.dispatchEvent(new ClipboardEvent('paste', { clipboardData, bubbles: true, cancelable: true }))
      }, text)
    }
    for (const [clipboard, numeric, display] of [
      ['Rp 1.234,56', 1234.56, '1.234,56'],
      ['1.234', 1234, '1.234'],
      ['1.234.567', 1234567, '1.234.567'],
      ['1,234.56', 1234.56, '1.234,56'],
      ['1000.50', 1000.5, '1.000,50'],
    ]) {
      await paste(clipboard)
      assert.equal(await amount.inputValue(), display, `clipboard ${clipboard}`)
      assert.equal((await state()).amount, numeric, `clipboard ${clipboard}`)
    }
    await amount.fill('1000.50')
    assert.equal((await state()).amount, 1000.5)
    assert.equal(await amount.inputValue(), '1.000,50')
    await input('Harga satuan').focus()
    assert.equal(await amount.inputValue(), '1.000,5')
    await amount.fill('')
    await amount.pressSequentially('0.01')
    assert.equal((await state()).amount, 0.01)
    assert.equal(await amount.inputValue(), '0,01')
    await amount.fill('')
    await amount.pressSequentially(',5')
    assert.equal((await state()).amount, 0.5)
    assert.equal(await amount.inputValue(), '0,5')
    assert.equal(await amount.evaluate(el => el.selectionStart), 3)
    console.log('PASS event paste rupiah/spreadsheet dan kompatibilitas titik/koma desimal')
    await amount.fill('12,')
    await amount.pressSequentially('50')
    assert.equal((await state()).amount, 12.5)
    assert.equal(await amount.inputValue(), '12,50')
    await input('Harga satuan').focus()
    assert.equal((await state()).amount, 12.5)
    await amount.fill('')
    assert.equal((await state()).amount, 0)
    assert.equal(await amount.inputValue(), '')
    console.log('PASS tempel format rupiah, koma desimal, nol desimal, dan pengosongan')

    await page.getByRole('button', { name: 'Muat nominal', exact: true }).click()
    assert.equal(await amount.inputValue(), '1.234.567')
    await amount.focus()
    await amount.evaluate(el => el.setSelectionRange(3, 3))
    await amount.pressSequentially('9')
    assert.equal(await amount.inputValue(), '12.934.567')
    assert.equal((await state()).amount, 12934567)
    assert.equal(await amount.evaluate(el => el.selectionStart), 4)
    await amount.press('Backspace')
    assert.equal(await amount.inputValue(), '1.234.567')
    assert.equal((await state()).amount, 1234567)
    assert.equal(await amount.evaluate(el => el.selectionStart), 3)
    await amount.evaluate(el => el.setSelectionRange(2, 2))
    await amount.press('Backspace')
    assert.equal(await amount.inputValue(), '234.567')
    assert.equal((await state()).amount, 234567)
    await page.getByRole('button', { name: 'Muat nominal', exact: true }).click()
    await amount.focus()
    await amount.evaluate(el => el.setSelectionRange(1, 1))
    await amount.press('Delete')
    assert.equal(await amount.inputValue(), '134.567')
    assert.equal((await state()).amount, 134567)
    await page.getByRole('button', { name: 'Muat HPP presisi', exact: true }).click()
    assert.equal(await input('Harga satuan').inputValue(), '1.234,5678')
    await input('Harga satuan').focus()
    await amount.focus()
    assert.equal((await state()).price, 1234.5678)
    assert.equal(await input('Harga satuan').inputValue(), '1.234,5678')
    console.log('PASS model eksternal, kursor, penghapusan pemisah ribuan, dan presisi HPP')

    assert(await input('Nominal nonaktif').isDisabled())
    assert(await input('Fieldset nonaktif').isDisabled())
    assert.equal(await input('Nominal terkunci').isEditable(), false)
    assert.equal((await state()).disabledAmount, 45000)
    assert.equal((await state()).readonlyAmount, 125000)
    await amount.fill('0')
    assert.equal(await valid(), false)
    await amount.fill('10000001')
    assert.equal(await valid(), false)
    await amount.fill('0,01')
    assert.equal(await valid(), true)
    const stepped = input('Kelipatan pembayaran')
    await stepped.fill('150')
    await page.getByRole('button', { name: 'Simpan kelipatan', exact: true }).click()
    assert.equal((await state()).stepSubmits, 0)
    await stepped.fill('200')
    await page.getByRole('button', { name: 'Simpan kelipatan', exact: true }).click()
    assert.equal((await state()).stepSubmits, 1)
    console.log('PASS disabled/readonly/fieldset dan batas min/max/kelipatan')

    await page.setViewportSize({ width: 390, height: 844 })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await page.getByRole('button', { name: 'Reset model', exact: true }).click()
    assert.equal((await state()).amount, 0)
    assert.equal(await input('Harga satuan').inputValue(), '1.234,56')
    assert.deepEqual(errors, [])
    console.log('PASS layout ponsel, reset model, dan tanpa galat Vue')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
