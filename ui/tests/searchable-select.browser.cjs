// Start Vite, then: SELECT_TEST_URL=http://127.0.0.1:4189 node tests/searchable-select.browser.cjs
// Requires Playwright with Chromium; no production API or database is used.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const base = process.env.SELECT_TEST_URL || 'http://127.0.0.1:4189'

;(async () => {
  const browser = await chromium.launch({ args: ['--no-sandbox'] })
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } })
    page.setDefaultTimeout(10000)
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.type() === 'warning' && message.text().includes('[Vue warn]')) errors.push(message.text()) })
    await page.goto(`${base}/tests/fixtures/searchable-select.html`)
    const state = async () => JSON.parse(await page.locator('#state').textContent())
    const picker = name => page.getByRole('combobox', { name, exact: true })
    async function choose(name, query, option) {
      await picker(name).click()
      await picker('Cari pilihan').fill(query)
      await page.getByRole('option', { name: option, exact: true }).click()
    }

    await page.getByRole('button', { name: 'Simpan', exact: true }).click()
    await picker('Cari pilihan').waitFor()
    assert.equal((await state()).submits, 0)
    await page.keyboard.press('Escape')
    assert.equal(await picker('Gudang wajib').getAttribute('aria-invalid'), 'true')
    await choose('Gudang wajib', '  INDUK ', 'Gudang Induk')
    assert.equal((await state()).warehouse, 'central')
    assert.equal((await state()).seenModel, 'central')
    assert.equal((await state()).changes, 1)
    assert.equal(await picker('Gudang wajib').getAttribute('aria-invalid'), null)
    const form = await page.locator('form').evaluate(el => Object.fromEntries(new FormData(el)))
    assert.equal(form.warehouse, 'central')
    console.log('PASS validasi wajib, label, formulir, dan urutan event perubahan')

    await choose('Jumlah baris', 'lima', 'Dua puluh lima')
    assert.equal((await state()).count, 25)
    assert.equal((await state()).countType, 'number')
    await choose('Jumlah baris', 'nol', 'Nol')
    assert.equal((await state()).count, 0)
    await choose('Nilai boolean', 'Ya', 'Ya')
    assert.equal((await state()).flag, true)
    await choose('Nilai boolean', 'Tidak', 'Tidak')
    assert.equal((await state()).flag, false)
    await choose('Satuan', 'botol', 'Botol')
    assert.equal((await state()).unit, 'botol')
    assert.equal((await state()).unitChanges, 1)
    await choose('Jenis AppSelect', 'satu', 'Satu')
    assert.equal((await state()).appValue, 1)
    assert.equal((await state()).appType, 'number')
    console.log('PASS angka termasuk nol, boolean, AppSelect, dan handler satuan')

    await picker('Gudang wajib').click()
    await picker('Cari pilihan').fill('nonaktif')
    assert.equal(await page.getByRole('option', { name: 'Gudang nonaktif' }).getAttribute('aria-disabled'), 'true')
    await page.keyboard.press('Enter')
    assert.equal((await state()).warehouse, 'central')
    await picker('Cari pilihan').fill('terlarang')
    assert.equal(await page.getByRole('option', { name: 'Gudang terlarang' }).getAttribute('aria-disabled'), 'true')
    await picker('Cari pilihan').fill('tidak ada hasil')
    await page.getByRole('status').getByText('Tidak ditemukan').waitFor()
    await page.keyboard.press('Escape')
    assert(await picker('Kontrol nonaktif').isDisabled())
    assert(await picker('Fieldset nonaktif').isDisabled())
    console.log('PASS pilihan/grup/fieldset nonaktif dan hasil kosong')

    await page.getByRole('button', { name: 'Muat item', exact: true }).click()
    await picker('Item asinkron').click()
    await page.getByRole('option', { name: 'Téh Melati' }).waitFor()
    await picker('Cari pilihan').fill('teh')
    await page.keyboard.press('Enter')
    assert.equal((await state()).item, 'tea')
    await page.getByRole('button', { name: 'Kosongkan item', exact: true }).click()
    assert((await picker('Item asinkron').textContent()).includes('Semua item'))
    await picker('Gudang wajib').focus()
    await page.keyboard.press('ArrowDown')
    await picker('Cari pilihan').fill('Outlet')
    await page.keyboard.press('Enter')
    assert.equal((await state()).warehouse, 'outlet')
    assert(await picker('Gudang wajib').evaluate(el => el === document.activeElement))
    await picker('Gudang wajib').click()
    await page.keyboard.press('Tab')
    assert(await picker('Jumlah baris').evaluate(el => el === document.activeElement))
    console.log('PASS opsi asinkron, reset data, pencarian aksen, dan keyboard')

    await choose('Komponen lama', 'Pilihan 99', 'Pilihan 99')
    assert.equal((await state()).searchValue, '99')
    await page.getByRole('button', { name: 'Pilih beberapa', exact: true }).click()
    const multiOptions = page.locator('.ss-options')
    await multiOptions.evaluate(el => { el.scrollTop = el.scrollHeight; el.dispatchEvent(new Event('scroll')) })
    assert(await page.locator('.ss-panel').isVisible())
    await page.locator('.ss-option').filter({ hasText: 'Pilihan 99' }).click()
    assert.deepEqual((await state()).multi, ['99'])
    await page.locator('.ss-backdrop').click({ position: { x: 2, y: 2 } })
    console.log('PASS komponen lama dan pencarian multi-pilih tetap berjalan')

    await page.setViewportSize({ width: 390, height: 844 })
    await picker('Gudang wajib').click()
    const rect = await page.locator('.ss-panel').boundingBox()
    assert(rect.x >= 0 && rect.x + rect.width <= 390)
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: 'Simpan', exact: true }).click()
    assert.equal((await state()).submits, 1)
    await page.getByRole('button', { name: 'Reset', exact: true }).click()
    await page.waitForFunction(() => JSON.parse(document.querySelector('#state').textContent).warehouse === '')
    assert.equal((await state()).count, 0)
    assert.equal((await state()).flag, false)
    assert.equal((await state()).appValue, 0)
    assert.deepEqual(errors, [])
    console.log('PASS layout ponsel, submit/reset, dan tanpa galat Vue')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
