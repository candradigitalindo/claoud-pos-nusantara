// Shared range-mode compatibility: no application API or production records.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const base = process.env.BALANCE_TEST_URL || 'http://127.0.0.1:4189'

;(async () => {
  const browser = await chromium.launch({ args: ['--no-sandbox'] })
  try {
    const page = await browser.newPage({ timezoneId: 'Asia/Jakarta', viewport: { width: 1000, height: 900 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.text().includes('[Vue warn]')) errors.push(message.text()) })
    await page.clock.setFixedTime(new Date('2026-11-02T02:00:00+07:00'))
    await page.goto(base + '/tests/fixtures/date-picker.html')
    const trigger = page.getByRole('button', { name: 'Rentang tanggal laporan', exact: true })
    const dialog = page.getByRole('dialog', { name: 'Pilih Rentang Tanggal', exact: true })
    const read = async () => JSON.parse(await page.locator('#selected-range').innerText())
    await trigger.click()
    await dialog.getByRole('button', { name: 'Bulan Lalu', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    assert.deepEqual(await read(), { from: '2026-10-01', to: '2026-10-31', label: 'Bulan Lalu' })

    await trigger.click()
    await dialog.locator('.drp-day[data-date="2026-10-29"]').click()
    assert(await dialog.getByRole('button', { name: 'Terapkan', exact: true }).isDisabled(), 'Range mode still requires an end date')
    await dialog.getByRole('button', { name: 'Bulan berikutnya', exact: true }).click()
    await dialog.locator('.drp-day[data-date="2026-11-01"]').click()
    assert(await dialog.getByRole('button', { name: 'Terapkan', exact: true }).isEnabled())
    await dialog.getByRole('button', { name: 'Terapkan', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    let value = await read()
    assert.equal(value.from, '2026-10-29'); assert.equal(value.to, '2026-11-01')
    console.log('PASS default range presets and cross-month two-date selection remain unchanged')

    await trigger.click()
    await dialog.locator('.drp-day[data-date="2026-11-02"]').click()
    await dialog.getByRole('button', { name: 'Bulan sebelumnya', exact: true }).click()
    await dialog.locator('.drp-day[data-date="2026-10-30"]').click()
    await dialog.getByRole('button', { name: 'Terapkan', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    value = await read()
    assert.equal(value.from, '2026-10-30'); assert.equal(value.to, '2026-11-02')
    await trigger.click()
    await dialog.locator('.drp-day[data-date="2026-11-01"]').click()
    await page.keyboard.press('Escape')
    await dialog.waitFor({ state: 'hidden' })
    assert.deepEqual(await read(), value)
    await trigger.click()
    await dialog.getByRole('button', { name: 'Semua Tanggal', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    assert.deepEqual(await read(), { from: '', to: '', label: 'Semua Tanggal' })
    assert.deepEqual(errors, [])
    console.log('PASS reverse selection, cancellation and optional all-dates mode remain compatible')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
